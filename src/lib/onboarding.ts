// src/lib/onboarding.ts — Единое условие «пользователю нужна доска».
//
// Онбординг — это не «профиль создан», а «нет ни одной доски». Эти два
// события принципиально разные по обратимости:
//
//   • профиль создаётся ОДИН раз и навсегда;
//   • доска создаётся сколько угодно раз, пока её нет.
//
// Раньше оба входа в приложение (роут `/` и модалка в `/flowboard`) решали
// «нужен ли онбординг» по `is_new_user` — флагу, который `/api/init`
// выставляет только в том HTTP-запросе, где профиль был создан. Из-за этого
// прерванный онбординг был необратим: профиль уже создан, на следующем
// запуске `is_new_user` становится `false`, и человек попадал на ПУСТУЮ
// доску вместо формы создания — выхода из этого состояния не было.
//
// Теперь условие выводится из состояния (`workspaces.length === 0`), а не из
// факта прошлого, поэтому прерывание онбординга безопасно: не создал доску —
// при следующем входе снова увидишь форму.
//
// Про инвайт: для нового пользователя с валидной ссылкой-приглашением
// `/api/init` возвращает `workspaces: [{ id, name: '', slug: '' }]`
// (api/init/route.ts, ветка accept_invite_link). Длина массива равна 1, поэтому
// `needsBoardCreation` возвращает false — приглашённому онбординг не
// показывается, как и задумано.

import type { InitResponse } from '../../types/api';

/**
 * Нужно ли показывать онбординг (создание первой доски)?
 *
 * Чистая функция — её результат целиком определяется переданными данными,
 * поэтому и вызывающий код, и тесты считают условие одинаково.
 *
 * @param data ответ `POST /api/init`
 * @returns true — у пользователя нет ни одной доски; false — доска есть
 *   либо данных нет вовсе (auth грузится или ошибка авторизации)
 */
export function needsBoardCreation(data: InitResponse | null | undefined): boolean {
  // Нет данных — вывода не делаем. Пока auth грузится, is_new_user/список
  // досок ещё неизвестны, и «нужен онбординг» означало бы редирект на
  // /board/create вместо экрана загрузки или ошибки авторизации.
  if (!data) return false;
  return (data.workspaces?.length ?? 0) === 0;
}
