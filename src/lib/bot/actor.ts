// src/lib/bot/actor.ts — определение актора Telegram-команды.
//
// Актор — это тот, кто НАПИСАЛ команду (`message.from`), а не автор
// процитированного сообщения. Разница критична для `/task` в реплае:
// у пересланного сообщения `reply_to_message.from` — это переславший его
// в чат, а не автор оригинала (исходный автор лежит в `forward_origin`,
// Bot API 7.0+). Подмена актора на автора реплая приводила к тому, что
// бот искал профиль чужого человека и отвечал «Профиль не найден.
// Начните с /start» — даже когда команда была отправлена вами.
//
// Вынесено в отдельный модуль, чтобы правило было покрыто тестом:
// webhook/route.ts — Route Handler с побочными эффектами, напрямую
// в vitest не тестируется.

/**
 * Telegram ID актора команды.
 *
 * Всегда `message.from.id` — независимо от наличия `reply_to_message`
 * и от того, было ли процитированное сообщение пересланным.
 * Возвращает undefined, если отправителя нет (например, сообщение от канала).
 */
export function resolveActorId(message: {
  from?: { id: number };
  reply_to_message?: { from?: { id: number }; forward_origin?: unknown };
}): number | undefined {
  return message.from?.id;
}
