-- 133_document_duplicate_rejection.sql
-- onitask · Запрет на загрузку документа, уже присутствующего в KB
--
-- Контекст (2026-09-27, долг фазы VEC-13):
--
-- SHA-256 содержимого вычисляется в Route Handler при загрузке (documents
-- route.ts, `computeChecksum`) и пишется в `workspace_documents.checksum`.
-- Раньше это значение нигде не читалось: повторная загрузка того же файла
-- создавала ВТОРОЙ документ со вторым набором чанков, а значит — вторую
-- копию векторов в `workspace_doc_chunks` и дубль в выдаче `match_doc_chunks`.
-- Смысл `match_doc_chunks` в том, что близкий контекст поднимает разные
-- чанки; два одинаковых документа тихо ухудшают этот контекст вдвое.
--
-- Политика (решение владельца): повторная загрузка идентичного содержимого —
-- ОШИБКА, а не замена. Обновление содержимого требует удаления старых
-- чанков, пересчёта эмбеддингов и возврата `status` в `processing`, то есть
-- это отдельная фича, а не побочное поведение загрузки. Практическое
-- следствие: обновить документ можно только удалив и загрузив заново
-- (DELETE в этом же маршруте каскадно уносит чанки).
--
-- Критерий — СОДЕРЖИМОЕ, а не имя файла. `DESIGN.md` и `design-copy.md` с
-- одинаковым байт-в-байт содержимым дают одинаковый SHA-256 и отклоняются.
--
-- Зачем индекс, если Route Handler всё равно проверяет: проверка в приложении
-- не защищает от гонки — два параллельных запроса оба увидят, что такого
-- документа нет, и оба вставят. Unique index делает утверждение обязательным
-- на уровне БД, независимо от того, кто пишет. Проверено: точка вставки в
-- `workspace_documents` по всему репозиторию ровно одна (documents route.ts),
-- `doc-process` только читает checksum и обновляет status/chunk_count.
--
-- `WHERE checksum IS NOT NULL` обязателен: колонка объявлена NOT NULL, но
-- partial-индекс страхует путь, где вставка случилась до простановки хеша —
-- такие строки не должны падать на конфликте вместо успешной вставки.
--
-- Перед созданием индекса проверено на данных: дублей нет (1 документ,
-- checksum заполнен, NULL отсутствуют).
--
-- Инварианты: RLS, CHECK-констрейнты, статусы и данные не изменяются.
-- ============================================================================

-- Гонка двух параллельных запросов не блокируется строчной блокировкой на
-- уровне приложения, поэтому уникальность обеспечиваем здесь.
CREATE UNIQUE INDEX IF NOT EXISTS uq_workspace_documents_ws_checksum
  ON public.workspace_documents (workspace_id, checksum)
  WHERE checksum IS NOT NULL;

COMMENT ON INDEX public.uq_workspace_documents_ws_checksum IS
  'Уникальность документа по паре (workspace_id, SHA-256 содержимого), миграция '
  '133, 2026-09-27. Повторная загрузка идентичного содержимого отклоняется. '
  'Partial: строки без checksum не участвуют в конфликте.';

-- Диагностика: сколько документов и сколько из них уникальны по содержимому.
-- Необходима, чтобы ловить дубли, проскочившие до включения индекса.
CREATE OR REPLACE FUNCTION public.document_duplicate_report()
RETURNS TABLE (
  workspace_id uuid,
  checksum     text,
  duplicates   bigint,
  filenames    text[]
)
LANGUAGE sql
STABLE
AS $$
  SELECT
    d.workspace_id,
    d.checksum,
    count(*),
    array_agg(d.filename ORDER BY d.created_at)
  FROM public.workspace_documents d
  WHERE d.checksum IS NOT NULL
  GROUP BY d.workspace_id, d.checksum
  HAVING count(*) > 1
  ORDER BY count(*) DESC;
$$;

COMMENT ON FUNCTION public.document_duplicate_report() IS
  'Показывает документы с одинаковым содержимым внутри workspace (миграция 133). '
  'Пустой результат — дублей нет. Нужен для проверки до и после включения '
  'уникального индекса.';
