-- INV-04: онбординг агентов переносится с DB-триггера на app-level upsert.
--
-- Проблема: триггер trg_auto_create_agent_worker создавал воркера-агента на
--   ЛЮБОЙ insert в agent_events. Webhook (миграция review_approval_workflow,
--   коммит c735e6c) пишет аудит человеческих действий с псевдо-именем
--   'telegram_user_<tg_id>' → каждый человек, нажавший «Согласовать»,
--   материализовался на доске как доступный для назначения агент-воркер
--   (кейс 25.08: worker telegram_user_425693173).
-- Решение: триггер удаляется; создание воркера выполняет
--   resolveAgentWorkerId() (lib/shared/mcpAuth.ts) — единственная точка,
--   привязанная к аутентифицированному MCP-ключу. Псевдо-агенты физически
--   не проходят через неё → фантóмы невозможны архитектурно.
-- Семантика для агентов не меняется: первый authenticated вызов по-прежнему
--   материализует воркера (find-or-create внутри резолва).
-- ============================================================================

DROP TRIGGER IF EXISTS trg_auto_create_agent_worker ON public.agent_events;
DROP FUNCTION IF EXISTS public.auto_create_agent_worker();